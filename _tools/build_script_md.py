"""从 PPT 备注导出可打印讲稿，并按时长比例分配每一页的秒数。"""

import sys

from pptx import Presentation

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

PPTX = "paper/世界语言赛博活力图谱_答辩PPT.pptx"
OUT = "paper/答辩讲稿.md"
TOTAL_SEC = 600

TITLES = [
    "封面", "问题：一条更隐蔽的流失", "现实意义：为什么这件事重要", "研究问题：拆成四个",
    "数据与方法：五个来源", "系统设计：四层架构", "六个视图：一条论证链",
    "创新点 1：把数据缺口可视化", "创新点 2：语系星群", "创新点 3：四套口径交叉验证",
    "创新点 4：三件交互", "发现的规律：四条结论", "结论与局限", "结束",
]
TIPS = [
    "停 2 秒再开口，让观众看清题目。" ,
    "指一下三个大数字，再回到「不存在」这三个字。",
    "三张卡片从左到右点一遍，最后落到「双重缺席」。",
    "语速加快，四个问题一口气念完，不要停顿解释。",
    "表格不求逐行念，只强调最后一句「口径互不相干」。",
    "这张图不用细讲，一句话带过，重点在「换数据不用改视图」。",
    "六张缩略图用手划一圈，只念每个视图的关键词。",
    "这是全场最重要的停顿点：先让观众看到矩阵，再解释「横带」。",
    "点一下地图上那块橙色区域，说明 146 门里只有 11 门有维基。",
    "四根条一起看——都往上走。这是一句话就能说服人的证据。",
    "快速过，不要念细节；重点是「文案数字实时计算」。",
    "放慢。每一行念完停 1 秒，第四行是全场的反转点。",
    "局限要主动说，显得诚实；展望一句话即可。",
    "鞠躬，等提问。",
]

prs = Presentation(PPTX)
notes = []
for sl in prs.slides:
    txt = ""
    if sl.has_notes_slide:
        txt = sl.notes_slide.notes_text_frame.text.strip()
    notes.append(txt)

total_chars = sum(len(n) for n in notes)
lines = [
    "# 答辩讲稿 · 世界语言赛博活力图谱",
    "",
    f"> 共 {len(notes)} 页，讲稿 {total_chars} 字，按 **10 分钟**（600 秒）分配。",
    "> 中文演讲的舒适语速约 190 字/分钟，这份稿子正好落在 9–10 分钟；",
    "> 若现场紧张讲快了，就在第 8、10、12 页多留两秒看图。",
    "",
    "**结构配比**：问题与意义 1′50″｜数据与系统 1′40″｜四个创新点 3′05″｜"
    "发现的规律 2′20″｜结论 55″",
    "",
    "---",
    "",
]
acc = 0.0
for i, (n, title, tip) in enumerate(zip(notes, TITLES, TIPS), start=1):
    sec = round(TOTAL_SEC * len(n) / total_chars) if total_chars else 0
    acc += sec
    lines += [
        f"## 第 {i:02d} 页 · {title}",
        "",
        f"⏱ **约 {sec} 秒**　（累计 {round(acc/60,1)} 分钟）",
        "",
        n,
        "",
        f"> 💡 {tip}",
        "",
        "---",
        "",
    ]
lines += [
    "## 可能被问到的问题（准备用）",
    "",
    "**Q：为什么用浏览量而不是文章数？**",
    "A：文章数可以被机器人灌水。Kornai 在 2013 年的论文里就警告过「波将金维基」——"
    "瓦洛夫语维基的文章数排第 37，但几乎全是机器生成的地理条目。浏览量不能这样造假。",
    "",
    "**Q：维基百科能代表整个互联网吗？**",
    "A：不能，这是明确的局限。但我用四套互不相干的记录口径做了交叉验证，"
    "方向一致，说明结论不是维基这一个数据源造成的。",
    "",
    "**Q：为什么只有 2,662 门语言，不是七千种？**",
    "A：因为 WALS 只收录了 2,662 门有语法记录的变体。这是个取舍："
    "用 WALS 换来了 192 个语法特征，代价是覆盖面。「数字在场率 10%」这个数字"
    "因此只在 WALS 的语言集合内成立，不能直接外推到全部七千种。",
    "",
    "**Q：创新点里哪个最有价值？**",
    "A：四套口径交叉验证。前两个（数据缺口可视化、语系星群）是表现手法上的创新，"
    "而这一个是方法论上的——它让结论从「我观察到」变成「四套数据都这么说」。",
    "",
]

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
print(f"  已生成 {OUT}")
print(f"  页数 {len(notes)}，讲稿 {total_chars} 字，估计 {round(TOTAL_SEC/60,1)} 分钟")
