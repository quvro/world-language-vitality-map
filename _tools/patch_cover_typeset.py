tb(s, 0.72, 1.5, 6.4, 0.4, "数据可视化与人机交互 · 课程研讨报告", 12, MUTED)
tb(s, 0.72, 2.05, 7.0, 2.2, "世界语言\\n赛博活力图谱", 52, INK, True, spacing=1.12)
rect(s, 0.72, 4.05, 1.1, 0.055, ACCENT)
