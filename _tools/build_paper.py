h2("2.3 跨源编码对齐：现成对照表 + 消歧规则")
para(
    "这是整个工程中最耗时、也最容易出错的一步，值得单独说明。"
    "需要强调的是：**编码对照本身并不需要自己发明**。"
    "ISO 639-1 与 639-3 的对照可以从 Wikidata 取得，"
    "WALS 的 languages.csv 本身就带有 Glottocode 与 ISO639P3code 两列，"
    "维基版本的真实域名可以直接读站点列表接口。这些都直接采用了。"
)
para(
    "真正的工作量在于**对照表之上的一层消歧规则**。原因是对照表并不是一个主键映射，"
    "而是一张多对多的关系图，直接 JOIN 会在几处静默出错："
)
para(
    "**其一，Glottocode 不能当主键。** 实测 3,573 行 WALS 只对应 2,502 个 Glottocode，"
    "其中 93 个 Glottocode 覆盖了 2 至 6 个真正不同的变体，而这 93 组里有 90 组的组内特征值互相冲突"
    "（例如 swis1247 之下同时装着阿尔萨斯语与五种瑞士德语方言）。"
    "若以 Glottocode 为键归并，等于在无人察觉的情况下把不同的语言合成了一条。"
    "因此本设计以 **WALS 的变体 ID 作为唯一分析单元**，Glottocode 只作为可回卷的分组键。",
    indent=True,
)
para(
    "**其二，一个 WALS 条目会被多个维基版本同时认领。** WALS 有时把两种语言合并在同一个条目里，"
    "例如阿塞拜疆语（aze）同时被 az 与 azb（南阿塞拜疆语）认领，"
    "印尼语（ind）同时被 id 与 ms（马来语）认领。对照表会返回多个候选而不给出选择，"
    "必须明文规定优先级：与 WALS 标注的 ISO 码一致者优先，其次是否为两字母的 ISO 639-1 码，"
    "再次关联时经过的步骤最少者，最后取总浏览量最高者。",
    indent=True,
)
para(
    "**其三，宏观语言与变体是一对多。** ISO 639-3 把普通话、粤语、闽南语各自单列"
    "（cmn / yue / nan），又把中文整体登记为一个宏观语言（zho）；"
    "而 WALS 按变体收录，所以拿 zho 去 WALS 里查询是查不到的。"
    "维基一侧的 zh 只有一个域名，却对应多门语言，流量归给谁同样需要决定。",
    indent=True,
)
para(
    "**其四，两套体系的码会撞。** WALS 自己的三字母码与 ISO 639-3 长得一样但语义不同："
    "WALS 的 deu 指德乌里语（Deuri），而 ISO 的 deu 是德语；"
    "WALS 的 aar 指 Aari，而 ISO 的 aar 是阿法尔语。"
    "其中德语这一侧尤其能说明问题——WALS 给它的是老式 ISO 639-2/B 码 ger，"
    "所以两门语言在两个体系里恰好把码换了个位置。这也是为什么绝不能拿 WALS 的 ID 充当 ISO 码，"
    "必须走 ISO639P3code 那一列。",
    indent=True,
)
para(
    "最后是关于域名的提醒：维基的域名确实就是 ISO 代码，但**可能是 639-1，也可能是 639-3**。"
    "本数据里 267 个有维基版本的语言中，153 个用两字母码、114 个用三字母码。"
    "例如中库尔德语的 639-1 是 ku，维基用的却是 639-3 的 ckb；"
    "粤语、吴语、闽南语则干脆没有 639-1 码，直接使用 yue / wuu / nan。"
    "因此不能假设「域名 = 两字母码」，而应当根据域名长度分别处理，"
    "并且始终从站点列表接口读取真实域名，而不是拿语言代码拼。"
)

