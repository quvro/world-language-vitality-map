# ----------------------------------------------------------------- 排版助手
def h1(text: str):
    p = doc.add_paragraph(text, style="Heading 1")
    for r in p.runs:
        r.font.size = Pt(16)
        r.font.bold = True
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(8)
    return p


def h2(text: str):
    """模板里的二级标题也是 Heading 1，只是字号小一号，这里沿用同样做法"""
    p = doc.add_paragraph(text, style="Heading 1")
    for r in p.runs:
        r.font.size = Pt(12)
        r.font.bold = True
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)
    return p


def para(text: str, indent: bool = True, size: float | None = None):
    """写一个正文段落。支持 **加粗** 标记 —— 直接写星号会在 Word 里留下字面量，
    所以按 ** 切段，奇数段设成粗体。"""
    p = doc.add_paragraph(style="Normal")
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run(seg)
        if i % 2 == 1:
            r.font.bold = True
        if size:
            r.font.size = Pt(size)
    pf = p.paragraph_format
    if indent:
        pf.first_line_indent = Cm(0.85)
    pf.space_after = Pt(6)
    pf.line_spacing = 1.45
    return p


def figure(name: str, caption: str, width_cm: float = 15.0):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(f"{FIG}/{name}.png", width=Cm(width_cm))
    c = doc.add_paragraph(style="Normal")
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(caption)
    r.font.size = Pt(10.5)
    c.paragraph_format.space_after = Pt(10)


def code(text: str):
    for line in text.strip("\n").split("\n"):
        p = doc.add_paragraph(style="Normal")
        r = p.add_run(line if line else " ")
        r.font.name = "Consolas"
        r.font.size = Pt(8.5)
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
        pf = p.paragraph_format
        pf.space_after = Pt(0)
        pf.line_spacing = 1.15
        pf.left_indent = Cm(0.7)
    doc.add_paragraph(style="Normal").paragraph_format.space_after = Pt(6)


def caption(text: str):
    """表注放在表格上方（中文论文惯例）"""
    p = doc.add_paragraph(style="Normal")
    r = p.add_run(text)
    r.font.size = Pt(10.5)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(3)
    return p


def kv_table(rows: list[tuple[str, ...]], header: tuple[str, ...], widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    try:
        t.style = "Table Grid"
    except KeyError:
        pass
    for i, cell in enumerate(t.rows[0].cells):
        cell.text = ""
        r = cell.paragraphs[0].add_run(header[i])
        r.font.bold = True
        r.font.size = Pt(10)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(v)
            r.font.size = Pt(9.5)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph(style="Normal").paragraph_format.space_after = Pt(8)
    return t


