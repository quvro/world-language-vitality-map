h1("三、数据集与可视化展示")

h2("3.1 数据集规模")
para(
    "最终数据集为 157,736 行、9 张表。核心语言表 2,662 门，其中 2,614 门有 ISO 639-3 码、"
    "2,645 门有 Glottocode、267 门（10.0%）拥有维基百科版本。"
    "时间序列覆盖 2015 年 7 月至 2026 年 9 月共 135 个月。"
)

h2("3.2 四个关键发现")
para(
    "**发现一：数字留存率较低。** 在 2,662 门有语法记录的语言里，"
    "只有 267 门拥有独立的维基百科版本，约为一成；也就是说，"
    "语言研究最关注的这批对象当中，九成在互联网上没有属于自己的入口。"
)
para(
    "**发现二：缺席是全局性的。** 把语言按语系、地区与结构特征分别分组统计，"
    "数字缺席的比例都没有实质变化：语言数不少于二十的十五个语系无一例外；"
    "而濒危等级与语法记录完整度之间的秩相关仅 −0.045，"
    "意味着「被记录得多不多」与「濒危不濒危」几乎是两件事。"
)
para(
    "**发现三：四套口径对语言活力的判断方向一致。** "
    "WALS 的语法特征记录数、Glottolog 的描写深度与文献数量、UNESCO 的濒危等级，"
    "这四套采集口径互不相干的资料，在判断「谁更活跃、谁更边缘」时方向一致。"
)
para(
    "**发现四：但数字空间也能替语言续命。** 濒危等级最高的那一档里仍有两门语言拥有维基版本，"
    "它们分别是康沃尔语与马恩岛语。康沃尔语的最后一位母语者于 1777 年去世，"
    "马恩岛语在 1974 年，作为口语它们都已消失；但在过去十年间，"
    "康沃尔语的维基百科月阅读量从 10.3 万次上升到 215 万次，是原来的 21 倍（涨幅 +2003%），"
    "马恩岛语的涨幅约为 +116%。也就是说，口语层面的消亡并不等于彻底消失，"
    "只要有持续的书写与阅读，数字空间可以替它把生命延续下去。"
)

h2("3.3 可视化如何支撑这些发现")
para(
    "四个发现分别对应四个视图：地图给出留存率，记录缺口图说明数据自身的不平等，"
    "濒危与关注视图把两种「活力」并置，流向图则把语系的流失方向一次呈现。"
    "值得强调的是，这些视图之间不是并列关系——记者的读法是从左到右一条链，"
    "而故事模式的八步正是按这条链设计的。"
)

