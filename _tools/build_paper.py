# ----------------------------------------------------------------- 四 价值
h1("四、价值与意义")

h2("4.1 数据是半自采的")
para(
    "五个来源里，WALS 与 Glottolog 的结构描写、Wikidata 的编码映射来自公开数据集，"
    "而各维基版本的规模、月度浏览量与每门语言的文献清单，是按接口逐条抓取并汇总的。"
    "也就是说，这份数据不是把现成表格拼起来，其中相当一部分需要自己采集、"
    "并且要处理限流、分页与接口变更。"
)

h2("4.2 真正的工作量在聚合")
para(
    "同一门语言的信息原本分散在四套互不相干的体系里：结构描写在 WALS，"
    "濒危评定在 UNESCO 与 Glottolog，文献目录在 Glottolog 的参考文献库，"
    "网络关注度在维基媒体的接口。它们各自使用自己的编号，无法直接连接，"
    "任何跨体系的比较都必须先解决对齐问题。本设计用一张 bridge_xref 表"
    "把每一次映射与裁决都记录下来，使整个对齐过程可审计、可复现。"
)

h2("4.3 一套可复用的三向编码对照")
para(
    "以 WALS 变体为分析单元、以 Glottolog 为枢纽，"
    "建立了 WALS 码、Glottocode 与 ISO 639-3 之间的三向映射，"
    "并明文规定了「一个条目被多个维基版本认领」时的优先级。"
    "这一层逻辑只与编码体系有关、与主题无关，因此具备被其他研究者复用的价值；"
    "对齐完成之后，按语法特征、语系、濒危等级与增长率任意组合筛选，只剩一次点击的距离。"
)

h2("4.4 真实性与可用性")
para(
    "所有数据均可通过公开接口或可复现脚本重新获得，七个采集脚本全部幂等；"
    "系统中每个统计数字都由同一份筛选结果实时计算，不预先写死，"
    "因此数据更新之后不会出现「图表变了、文案还是旧数字」的情况。"
)

h2("4.5 感知性与可行性")
para(
    "视觉编码遵循「一个通道一个维度」的原则：位置用于地理，颜色用于语区或濒危等级，"
    "大小用于关注度，形状用于复合字形。当维度超过可用通道时，采用可开关的复合字形"
    "而不是把所有信息压进一个点。整站采用浅色主题与低饱和配色，长时间阅读不易疲劳。"
)

h2("4.6 艺术性与设计性")
para(
    "系统没有套用现成的仪表盘模板。标题区用「10.0%」这个数字作为视觉锚点，"
    "地图、图表与文案共用一套衬线无衬线的版式语言，"
    "交互文案统一使用陈述句而非「点击查看」这类操作指令。"
)

h2("4.7 原创性与有价值")
para(
    "原创性体现在三处：把「数据缺口」本身做成可视化对象，而不是回避它；"
    "用复合字形在同一位置编码五个维度并允许逐通道关闭；"
    "以及用秩相关为「四套口径一致」这一结论提供可检验的依据。"
    "价值则在于它把分散的资料接成了一张可以查询、可以比较、可以引用的表。"
)

# ----------------------------------------------------------------- 五 结论
h1("五、结论与展望")

h2("5.1 四个结论")
para(
    "**结论一：数字留存率约为一成。** 在 2,662 门有语法记录的语言里，"
    "只有 267 门拥有独立的维基百科版本。"
)
para(
    "**结论二：数字缺席是全局性的。** 语言数不少于二十的十五个语系无一例外，"
    "且濒危等级与语法记录完整度的秩相关仅 −0.045——"
    "缺席不是某些语系或某些地区的特例，而是一条全局规律。"
)
para(
    "**结论三：四套指标对语言活力的判断方向一致但不冗余。** "
    "八对秩相关全部显著同向，而 |ρ| 仅为 0.05–0.32，"
    "说明它们彼此独立却指向同一方向，这个结论不是某一个数据源的偏差。"
)
para(
    "**结论四：网络传播能让已经消失的口语重新被看见。** "
    "康沃尔语与马恩岛语的最后一位母语者分别在 1777 年与 1974 年去世，"
    "但这两门语言的维基百科月阅读量十年间分别上升约 2003% 与 116%，"
    "其中康沃尔语当前每月被阅读约 215 万次。数字入口本身，就是语言被保护的一种可能。"
)

h2("5.2 三个可继续拓展的方向")
para(
    "**第一，把覆盖推到全部语言。** 现在的分析建立在 WALS 收录的 2,662 门有语法记录的变体之上，"
    "而世界上的语言远多于此。接入 Glottolog 的全量语言与濒危语言名录，"
    "把分母扩展到七千量级之后，「数字留存率一成」才有可能成为可外推的全球判断。"
)
para(
    "**第二，从单一平台扩到多平台对照。** 维基百科只是互联网的一个切面，"
    "阅读量还容易被新闻事件与病毒式传播带动。若把同一套方法用到视频平台、"
    "社交平台与搜索指数上，就能检验这条规律是否跨平台成立；"
    "若四五个平台方向一致，结论的稳健性会完全不同。"
)
para(
    "**第三，把一条时间序列读得更细。** 现在用首尾比值衡量十年变化，只能得到「涨了还是跌了」。"
    "改用趋势检验与变点检测，可以定位每门语言关注度的转折年份——"
    "像康沃尔语这样的语言，究竟是哪一年、因为什么重新被看见，"
    "都能落到具体的时间点上，从而把「在涨」变成「从什么时候开始涨、为什么涨」。"
)

h2("5.3 需要说明的局限")
para(
    "本设计的结论只在 WALS 收录的语言集合内成立，不能直接外推到全部七千种语言；"
    "维基百科也不能代表整个互联网。此外，增长率目前用首尾比值计算，"
    "对基线过小的语言会失真（例如塞德克语的 +10,270%，其基线期月阅读量只有个位数），"
    "这也是上节第二条拓展方向要解决的问题。"
)

