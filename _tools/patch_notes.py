"""把 PPT 讲稿补到约 2,100 字（10 分钟语速）。"""

import io
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

P = "_tools/build_ppt.py"
s = io.open(P, encoding="utf-8").read()

PAIRS = [
    # 02 收尾更狠一点
    ('"这就是我说的赛博活力的缺席。")',
     '"这里的关键区别是——不是内容太少，是连一个可以持续更新的入口都没有。"\n'
     '        "而这种缺席不会发出任何声响，没有任何报错。")'),
    # 03 点明本项目只回答哪一半
    ('"所以把数字存亡可视化，不是猎奇，是真实需求。")',
     '"所以这个项目要回答的不是「哪种语言快死了」——那是语言学的事；"\n'
     '        "而是「哪种语言已经在网上消失了」，这是数据能回答的那一半。")'),
    # 05 交代采集难度
    ('"才能说明它不是某个数据集的偏差。")',
     '"才能说明它不是某个数据集的偏差。"\n'
     '        "采集本身也不轻松：两套语言代码标准要转换，宏观语言的码在 WALS 里根本不存在，"\n'
     '        "还有七个维基版本的域名猜不出来。这些坑都写进了代码注释。")'),
    # 07 让每个视图都有落点
    ('"记录缺口回答数据本身有多不可靠，濒危与关注回答两种活力是否一致，流向回答往哪边走。")',
     '"记录缺口这张最特殊——它不展示语言，展示的是数据本身有多不可靠；"\n'
     '        "濒危与关注回答两种活力是否一致；流向用桑基图回答语言正往哪一边走。"\n'
     '        "这六个视图不是六张独立的图，而是同一条论证链上的六步。")'),
    # 12 收束回开头的问题
    ('"所以数字空间既能抛弃一种语言，也能替它续命。")',
     '"这两门语言作为口语都已经消失，一个在 1777 年、一个在 1974 年，"\n'
     '        "但在数字空间里反而在增长。所以数字空间既能抛弃一种语言，也能替它续命。"\n'
     '        "这也回答了最开始那个问题：被抛下的不是「快要消失的语言」，"\n'
     '        "而是「从来没有被记录过的语言」。")'),
    # 13 展望 + 收尾
    ('ELCat 的资源清单。")',
     'ELCat 的资源清单，把数字在场扩展到维基百科之外。")'),
]

hit = 0
for old, new in PAIRS:
    if old in s:
        s = s.replace(old, new, 1)
        hit += 1
    else:
        print("  未匹配：", old[:46])

io.open(P, "w", encoding="utf-8").write(s)
print(f"  替换 {hit}/{len(PAIRS)} 处")
