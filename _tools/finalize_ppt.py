"""裁封面、重建 PPT、并据新结构重新导出讲稿 md。"""

import io
import re
import subprocess
import sys

from pptx import Presentation

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# ---------------------------------------------------------------- 1) 裁封面
P = "_tools/build_ppt2.py"
s = io.open(P, encoding="utf-8").read()
old = "shot.crop_left = shot.crop_right = 0.2075"
new = (
    "shot.crop_left = shot.crop_right = 0.291\n"
    "shot.crop_top, shot.crop_bottom = 0.10, 0.16\n"
    "# 裁掉应用顶栏与底部时间轴/提问框，只留地图本体。\n"
    "# 裁剪比例按「裁剪后的宽高比必须等于画框比 6.783/7.5」倒推，否则会拉伸变形。"
)
if old in s:
    s = s.replace(old, new, 1)
    io.open(P, "w", encoding="utf-8").write(s)
    print("  封面裁剪已更新")
else:
    print("  封面裁剪已是新值（跳过）")

# ---------------------------------------------------------------- 2) 重建
r = subprocess.run([sys.executable, P], capture_output=True, text=True,
                   encoding="utf-8", errors="replace")
print("  " + (r.stdout or r.stderr).strip().splitlines()[-1])

# ---------------------------------------------------------------- 3) 讲稿 md
TITLES = [
    ("封面", "停 2 秒再开口，让老师看清题目。"),
    ("目录", "四句话带过，不要念细节。"),
    ("章节页 · 一", "直接翻过去，别停。"),
    ("研究背景：一条更隐蔽的流失", "指三个大数字，再回到「不存在」三个字。"),
    ("★ 2,662 个格子", "**全场最重要的图。** 讲慢，用手比一下上下两半。"),
    ("现实意义：为什么这件事重要", "三张卡片从左到右点一遍，落到「双重缺席」。"),
    ("研究问题：四个", "一口气念完，不要停顿解释。"),
    ("章节页 · 二", "直接翻过去。"),
    ("五个数据源", "表格不求逐行念，只强调「口径互不相干」。"),
    ("四层架构", "一句话带过，重点在「换数据不用改视图」。"),
    ("六个视图", "六张缩略图划一圈，只念关键词。"),
    ("章节页 · 三", "停一下，说「这部分我最想讲」。"),
    ("创新点 1：数据缺口", "先让老师看到矩阵，再解释「横带」。"),
    ("创新点 2：语系星群", "点一下图上那块橙色区域。"),
    ("创新点 3：四套口径", "四根条一起看——都往上走。这是最抗问的一页。"),
    ("创新点 4：交互", "快速过，重点是「文案数字实时计算」。"),
    ("章节页 · 四", "直接翻过去。"),
    ("四条结论", "**放慢。** 每行念完停 1 秒，第四行是反转点。"),
    ("流向图", "指最右边的分叉，说明「都汇入同一侧」。"),
    ("结论与局限", "局限主动说，显得诚实。"),
    ("End", "鞠躬，等提问。"),
]

prs = Presentation("paper/世界语言赛博活力图谱_答辩PPT.pptx")
notes = [sl.notes_slide.notes_text_frame.text.strip() if sl.has_notes_slide else ""
         for sl in prs.slides]
total = sum(len(n) for n in notes)
TOTAL_SEC = 630  # 章节页几乎不说话，所以总时长略大于纯文字估算

lines = [
    "# 答辩讲稿 · 世界语言赛博活力图谱",
    "",
    f"> {len(notes)} 页 · 讲稿 {total} 字 · 目标 **10–11 分钟**",
    "> 中文演讲舒适语速约 190 字/分钟，这份稿子约 11 分钟；",
    "> 若超时，优先压缩第 9 页（数据源表格）和第 16 页（交互）。",
    "",
    "**结构**：问题与意义 2′10″｜数据与系统 1′40″｜四个创新点 3′10″｜"
    "规律与结论 2′30″｜收尾 30″",
    "",
    "---",
    "",
]
acc = 0.0
for i, (n, (title, tip)) in enumerate(zip(notes, TITLES), start=1):
    sec = round(TOTAL_SEC * len(n) / total) if total else 0
    acc += sec
    lines += [f"## 第 {i:02d} 页 · {title}", "",
              f"⏱ **约 {sec} 秒**　（累计 {round(acc/60, 1)} 分钟）", "", n, "",
              f"> 💡 {tip}", "", "---", ""]

lines += [
    "## 可能被问到的问题（准备好）",
    "",
    "**Q：为什么用浏览量而不是文章数？**",
    "A：文章数能被机器人灌水。Kornai 2013 年就警告过「波将金维基」——"
    "瓦洛夫语维基文章数排第 37，几乎全是机器生成的地理条目。浏览量造不了假。",
    "",
    "**Q：维基百科能代表整个互联网吗？**",
    "A：不能，这是明确的局限。所以我用四套互不相干的记录口径做交叉验证，"
    "方向一致，说明结论不是维基这一个源造成的。",
    "",
    "**Q：为什么只有 2,662 门，而不是七千种？**",
    "A：WALS 只收录了 2,662 门有语法记录的变体。这是取舍："
    "换来 192 个语法特征，代价是覆盖面。所以「10%」这个数字"
    "只在 WALS 的语言集合内成立，不能直接外推到全部七千种。",
    "",
    "**Q：哪个创新最有价值？**",
    "A：四套口径交叉验证。前两个是表现手法，第三个是方法论——"
    "它让结论从「我观察到」变成「四套数据都这么说」。",
    "",
    "**Q：那张格子图（2,662 个格子）算创新吗？**",
    "A：手法不新（单位图 / unit chart 是经典），但我把它用在了对的地方："
    "10% 这个数字读起来没感觉，画成 2,662 个格子才有体感。"
    "而且它顺带说明了最反直觉的一点——最健康的那一档也八成是空的。",
    "",
]
io.open("paper/答辩讲稿.md", "w", encoding="utf-8").write("\n".join(lines))
print(f"  讲稿 md 已更新：{len(notes)} 页，{total} 字")
